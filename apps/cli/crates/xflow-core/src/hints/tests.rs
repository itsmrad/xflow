#[test]
fn selection_is_fast() {
    let mut config = Config::default();
    config.dictionary.words = (0..50).map(|i| format!("Word{i}")).collect();
    config.dictionary.words.push("BigQuery".into());
    let title = vec!["useAuth.ts".to_string(), "terraform-aws".to_string()];
    let mut recent = Recent::default();
    recent.note("Amazon EKS and Amazon SQS with kubectl and Azure Key Vault and BigQuery");
    let signals = Signals {
        terminal: true,
        app: Some("com.apple.Terminal"),
        title: &title,
        recent: recent.terms(),
    };
    select(&config, &signals);
    let start = std::time::Instant::now();
    for _ in 0..100 {
        std::hint::black_box(select(&config, &signals));
    }
    // ~30 µs in release; generous for unoptimised, loaded CI runners.
    assert!(
        start.elapsed() < std::time::Duration::from_millis(500),
        "{:?}",
        start.elapsed()
    );
}
