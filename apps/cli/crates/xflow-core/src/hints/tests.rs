use super::*;
use std::collections::HashSet;

fn hand(group: usize) -> Vec<&'static str> {
    sections()
        .iter()
        .find(|s| s.name == GROUPS[group])
        .map(|s| s.body.lines().collect())
        .unwrap_or_default()
}

fn group_of(term: &str) -> usize {
    sections()[lookup(term).unwrap().1].group
}

fn hand_group(term: &str) -> Option<usize> {
    (0..4).find(|&g| hand(g).contains(&term))
}

fn at<'a>(terminal: bool, app: Option<&'a str>) -> Signals<'a> {
    Signals {
        terminal,
        app,
        ..Signals::default()
    }
}

#[test]
fn lexicon_is_unique_plain_bounded_and_never_ordinary_english() {
    let lines: Vec<&str> = LEXICON.lines().collect();
    assert!(lines[0].starts_with("# Generated by scripts/lexicon/build.py"));
    let mut seen = HashSet::new();
    let (mut count, mut generated) = (0, false);
    for line in &lines[1..] {
        if let Some(header) = line.strip_prefix('@') {
            let (name, group) = header.split_once(' ').unwrap();
            generated = !GROUPS.contains(&name);
            assert!(GROUPS.contains(&group), "{header}");
            assert!(name.bytes().all(|b| b.is_ascii_lowercase()), "{header}");
            continue;
        }
        let term = *line;
        count += 1;
        assert!(seen.insert(term.to_ascii_lowercase()), "duplicate {term}");
        assert!(
            term.len() >= 2
                && term.len() <= 24
                && term.trim() == term
                && !term.contains("  ")
                && term.split(' ').count() <= 3
                && term.chars().all(|c| c.is_ascii_graphic() || c == ' ')
                // `, ` joins the Whisper prompt; OpenAI rejects <, >.
                && !term.contains([',', '<', '>', '"', '{', '}', '[', ']', '\\'])
                && !term.bytes().all(|b| b.is_ascii_digit()),
            "{term:?}"
        );
        // Transcript-like terms only: no sentences or instructions.
        assert!(!term.ends_with(['.', ':', '!', '?']), "{term}");
        assert!(
            !term.split(' ').any(|w| matches!(
                w.to_lowercase().as_str(),
                "spell"
                    | "write"
                    | "use"
                    | "not"
                    | "never"
                    | "always"
                    | "instead"
                    | "ignore"
                    | "transcribe"
                    | "glossary"
            )),
            "{term}"
        );
        // A one-word hint biases casing too: everyday English stays out unless
        // its spelling sets it apart (TypeScript, S3, Next.js, AWS).
        let shaped = term
            .as_bytes()
            .windows(2)
            .any(|w| w[0].is_ascii_lowercase() && w[1].is_ascii_uppercase())
            || term.bytes().any(|b| b.is_ascii_digit())
            || term
                .as_bytes()
                .windows(2)
                .any(|w| w[0].is_ascii_alphanumeric() && b".-_+#@/".contains(&w[1]))
            || term.len() >= 3
                && term
                    .trim_end_matches('s')
                    .bytes()
                    .all(|b| b.is_ascii_uppercase());
        assert!(
            term.contains(' ') || shaped || !crate::words::common(&term.to_lowercase()),
            "{term} is everyday English"
        );
        // A phrase of plain lowercase words is something Whisper already hears
        // (the generator's rule; hand-kept heads were reviewed one by one).
        assert!(
            !generated
                || !term.contains(' ')
                || !term
                    .split(' ')
                    .all(|w| w.bytes().all(|b| b.is_ascii_lowercase()) && crate::words::common(w)),
            "{term} is a plain phrase"
        );
    }
    assert!(count >= 2_000, "{count} terms");
    assert!(LEXICON.len() < 96 * 1024, "{} bytes", LEXICON.len());
    // Every hand-kept head heads its own section, and every term is found.
    for (g, name) in GROUPS.iter().enumerate() {
        assert!(!hand(g).is_empty(), "{name}");
    }
    assert_eq!(index().len(), count);
    for line in lines[1..].iter().filter(|l| !l.starts_with('@')) {
        assert_eq!(lookup(&line.to_uppercase()).unwrap().0, *line);
    }
    for term in [
        "Amazon S3",
        "Google Kubernetes Engine",
        "Azure Key Vault",
        "kubectl",
    ] {
        assert!(lookup(term).is_some(), "{term}");
    }
    for term in [
        "cloud",
        "the",
        "linked list",
        "Lambda",
        "Monitor",
        "Excel",
        "",
    ] {
        assert!(lookup(term).is_none(), "{term}");
    }
}

#[test]
fn defaults_hint_dev_and_corp_and_the_focused_app_first() {
    let config = Config::default();
    // Mail, or focus not known yet: dev and corp interleaved; no sheet, no finance.
    let mail = select(&config, &at(false, Some("com.apple.mail")));
    assert_eq!(
        mail[..4],
        ["Claude", "Salesforce", "Claude Code", "HubSpot"]
    );
    assert_eq!(select(&config, &Signals::default()), mail);
    assert!(mail.iter().all(|t| matches!(group_of(t), 0 | 1)));
    // Terminals and editors: dev first, the hand-kept head before the lexicon.
    for (terminal, app) in [
        (true, Some("com.apple.Terminal")),
        (false, Some("com.microsoft.VSCode")),
        (false, Some("code.desktop")),
    ] {
        let got = select(&config, &at(terminal, app));
        assert_eq!(got[..MAX * 2 / 3], hand(0)[..MAX * 2 / 3], "{app:?}");
        assert!(
            got[MAX * 2 / 3..].iter().all(|t| group_of(t) == 1),
            "{app:?}"
        );
    }
    // Spreadsheets: every sheet term first, then dev and corp; finance stays off.
    for app in [
        "com.microsoft.Excel",
        "com.apple.iWork.Numbers",
        "libreoffice-calc",
    ] {
        let got = select(&config, &at(false, Some(app)));
        let sheet = hand(2).len();
        assert_eq!(got[..sheet], hand(2)[..], "{app}");
        assert!(got[sheet..]
            .iter()
            .all(|t| matches!(hand_group(t), Some(0 | 1))));
        assert!(got.contains(&"XLOOKUP") && !got.contains(&"EBITDA"));
    }
    for app in [None, Some("com.apple.mail"), Some("com.microsoft.Excel")] {
        let got = select(&config, &at(true, app));
        assert_eq!(got.len(), MAX);
        assert_eq!(got.iter().collect::<HashSet<_>>().len(), MAX);
    }
}

#[test]
fn config_turns_groups_and_hints_on_and_off() {
    let mut config = Config::default();
    config.vocab.finance = true;
    assert!(select(&config, &Signals::default())[..3].contains(&"EBITDA"));
    config.vocab = crate::config::VocabConfig {
        dev: false,
        corp: false,
        sheet: false,
        finance: false,
    };
    assert!(select(&config, &Signals::default()).is_empty());
    // The focused app still turns its own group on, hand-kept head first.
    let terminal = select(&config, &at(true, None));
    assert_eq!(terminal, hand(0));
    // Signals never reach a group that is off.
    let recent = ["EBITDA", "Amazon EKS"];
    let got = select(
        &config,
        &Signals {
            terminal: true,
            recent: &recent,
            ..Signals::default()
        },
    );
    assert_eq!(got[0], "Amazon EKS");
    assert!(!got.contains(&"EBITDA") && got.iter().all(|t| group_of(t) == 0));
    config.stt.domain_hints = false;
    for terminal in [false, true] {
        let s = Signals {
            recent: &recent,
            ..at(terminal, Some("com.microsoft.Excel"))
        };
        assert!(select(&config, &s).is_empty());
    }
}

#[test]
fn recent_terms_and_their_sections_come_first() {
    let config = Config::default();
    let mut recent = Recent::default();
    recent.note("Then we moved the queue to amazon sqs and wired up Amazon EKS.");
    recent.note("Ship it with kubectl.");
    assert_eq!(recent.terms(), ["kubectl", "Amazon SQS", "Amazon EKS"]);
    let got = select(
        &config,
        &Signals {
            terminal: true,
            recent: recent.terms(),
            ..Signals::default()
        },
    );
    assert_eq!(got[..3], ["kubectl", "Amazon SQS", "Amazon EKS"]);
    // The AWS head follows within Whisper's ~20 terms, before #117's list.
    let aws = &sections()[lookup("Amazon EKS").unwrap().1];
    assert_eq!(aws.name, "aws");
    let head: Vec<_> = aws.body.lines().take(8).collect();
    assert!(
        got[3..20].iter().filter(|t| head.contains(t)).count() >= 4,
        "{:?}",
        &got[..20]
    );
    assert_eq!(got.len(), MAX);
    assert_eq!(got.iter().collect::<HashSet<_>>().len(), MAX);
    // Dictionary words vote too, without being repeated as shipped terms.
    let mut config = Config::default();
    config.dictionary.words = vec!["BigQuery".into(), "Cloud Run".into()];
    let got = select(&config, &at(true, None));
    let gcp = &sections()[lookup("BigQuery").unwrap().1];
    assert_eq!(gcp.name, "gcp");
    assert!(
        gcp.body
            .lines()
            .next()
            .is_some_and(|t| got[..8].contains(&t)),
        "{got:?}"
    );
    // The recent list is bounded and most recent first.
    let mut recent = Recent::default();
    for t in hand(0).iter().take(40) {
        recent.note(t);
    }
    assert_eq!(recent.terms().len(), RECENT);
    assert_eq!(recent.terms()[0], hand(0)[39]);
    recent.clear();
    assert!(recent.terms().is_empty());
}

#[test]
fn title_words_pick_sections_but_are_never_sent() {
    let config = Config::default();
    let title = vec!["terraform-aws-vpc".to_string(), "Amazon EKS".to_string()];
    let recent = ["Amazon EKS", "kubectl"];
    let got = select(
        &config,
        &Signals {
            terminal: true,
            title: &title,
            recent: &recent,
            ..Signals::default()
        },
    );
    assert_eq!(got[0], "kubectl");
    for term in &got {
        for word in term.split(' ') {
            assert!(
                ![
                    "terraform",
                    "aws",
                    "vpc",
                    "amazon",
                    "eks",
                    "terraform-aws-vpc"
                ]
                .contains(&word.to_lowercase().as_str()),
                "{term} shares a title word"
            );
        }
    }
    // The title still pointed at AWS: its head (minus title words) comes early.
    let aws = &sections()[lookup("Amazon EKS").unwrap().1];
    assert!(
        got[..20].iter().any(|t| aws.body.lines().any(|l| l == *t)),
        "{got:?}"
    );
}

